#!/usr/bin/env python3
"""Turn Vim's command index (:help index, runtime/doc/index.txt) into
crates/core/data/vim-index.tsv: mode, section, tag, keys, description.

    scripts/vim-index.py [/usr/share/vim/vim91/doc/index.txt]

Vim's documentation is distributed under the Vim license; only the tags,
keys and one-line descriptions are kept here.
"""
import glob
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else sorted(glob.glob("/usr/share/vim/vim*/doc/index.txt"))[-1]
out_path = "crates/core/data/vim-index.tsv"

# Section headers and the mode/section they start, by help tag.
SECTIONS = {
    "insert-index": ("insert", "insert"),
    "normal-index": ("normal", "normal"),
    "objects": ("normal", "text-objects"),
    "CTRL-W": ("normal", "windows"),
    "[": ("normal", "brackets"),
    "g": ("normal", "g"),
    "z": ("normal", "z"),
    "operator-pending-index": ("normal", "operator-pending"),
    "visual-index": ("visual", "visual"),
    "ex-edit-index": ("cmdline", "cmdline-editing"),
    "terminal-job-index": ("terminal", "terminal"),
    "ex-cmd-index": ("ex", "ex"),
}

mode, section = None, None
rows = []
entry = None
for line in open(src, encoding="utf-8", errors="replace"):
    line = line.rstrip("\n")
    tags = [t for t in re.findall(r"\*([^*\s]+)\*", line) if t in SECTIONS]
    if tags and not line.startswith("|"):
        mode, section = SECTIONS[tags[0]]
        entry = None
        continue
    if mode is None:
        continue
    m = re.match(r"^\|([^|]+)\|\t+(\S.*?)\t+(.*)$", line)
    if m:
        tag, keys, desc = m.group(1), m.group(2).strip(), m.group(3).strip()
        entry = [mode, section, tag, keys, desc]
        rows.append(entry)
    elif entry and re.match(r"^\t\t\t", line) and line.strip() and not line.strip().startswith("|"):
        entry[4] = (entry[4] + " " + line.strip()).strip()
    elif not line.startswith("\t"):
        entry = None

with open(out_path, "w") as f:
    f.write("# Generated by scripts/vim-index.py from Vim's :help index. Vim license.\n")
    f.write("mode\tsection\ttag\tkeys\tdescription\n")
    for r in rows:
        f.write("\t".join(c.replace("\t", " ") for c in r) + "\n")
print(f"{len(rows)} commands -> {out_path}")
